import { chromium } from "/opt/node-tools/node_modules/playwright/index.mjs";
const b = await chromium.launch();
const pg = await b.newPage({ viewport: { width: 1400, height: 900 } });
const errs = [];
pg.on("pageerror", (e) => errs.push(`PAGEERROR ${e.message}`));
pg.on("response", (r) => { if (r.url().includes("/api/") && r.status() >= 400) errs.push(`${r.status()} ${r.url()}`); });
await pg.goto("http://localhost:3100/daten", { waitUntil: "networkidle" });
await pg.waitForTimeout(1500);
console.log("tables in sidebar:", await pg.locator('[data-testid="table-list"] li').count());
await pg.click('[data-testid="table-list"] >> text=order_positions');
await pg.waitForTimeout(1500);
console.log("count text:", await pg.locator('[data-testid="db-pager-count"]').innerText());
await pg.fill('[data-testid="db-q"]', "Artikel 3");
await pg.press("[data-testid=\"db-q\"]", "Enter");
await pg.waitForTimeout(1500);
console.log("after search:", await pg.locator('[data-testid="db-pager-count"]').innerText());
await pg.check('[data-testid="write-toggle"]');
await pg.locator('[data-testid="db-grid"] tbody tr').first().locator("button").first().click();
await pg.waitForSelector('[data-testid="row-editor"]');
await pg.waitForTimeout(800);
const unit = pg.locator('[data-testid="row-editor"] input').nth(3);
console.log("editor inputs:", await pg.locator('[data-testid="row-editor"] input').count());
await pg.screenshot({ path: "/tmp/daten2.png" });
console.log("errors:", errs.join(" | ") || "none");
await b.close();
